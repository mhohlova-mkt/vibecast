const CYRILLIC: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'i',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
}

/** Короткая читаемая часть URL: первые четыре слова заголовка. */
export function articleSlugBase(title: string): string {
  const latin = Array.from(title.toLocaleLowerCase('ru'))
    .map((character) => CYRILLIC[character] ?? character)
    .join('')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')

  return latin.split('_').filter(Boolean).slice(0, 4).join('_') || 'article'
}

export function articlePath(article: { id: string; slug?: string | null }): string {
  return `/text/${encodeURIComponent(article.slug || article.id)}`
}
